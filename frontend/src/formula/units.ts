/**
 * Русские обозначения единиц и имена math.js (общие для калькулятора 5.3b и
 * блока «Дано / СИ» физики 7.1b). Модуль без math.js — его можно подключать
 * в основной код, не загружая библиотеку.
 */

/** Русские обозначения единиц → имена math.js. Порядок важен для обратного перевода. */
export const UNITS: [string, string][] = [
  ['мм', 'mm'], ['см', 'cm'], ['дм', 'dm'], ['км', 'km'], ['м', 'm'],
  ['мг', 'mg'], ['кг', 'kg'], ['г', 'g'], ['т', 'tonne'],
  ['мс', 'ms'], ['мин', 'minute'], ['ч', 'h'], ['сут', 'day'], ['с', 's'],
  ['кН', 'kN'], ['Н', 'N'], ['кДж', 'kJ'], ['МДж', 'MJ'], ['Дж', 'J'], ['кВт', 'kW'], ['МВт', 'MW'], ['Вт', 'W'],
  ['кПа', 'kPa'], ['МПа', 'MPa'], ['Па', 'Pa'], ['атм', 'atm'], ['бар', 'bar'],
  ['мА', 'mA'], ['А', 'A'], ['кВ', 'kV'], ['мВ', 'mV'], ['В', 'V'], ['кОм', 'kohm'], ['МОм', 'Mohm'], ['Ом', 'ohm'],
  ['мКл', 'mC'], ['Кл', 'C'], ['кГц', 'kHz'], ['МГц', 'MHz'], ['Гц', 'Hz'], ['мкФ', 'uF'], ['Ф', 'F'], ['Тл', 'T'], ['Гн', 'H'],
  ['мл', 'mL'], ['л', 'L'], ['К', 'K'], ['моль', 'mol'], ['эВ', 'eV'], ['кВтч', 'kWh'], ['град', 'deg'], ['рад', 'rad'],
];

export const RU_TO_EN = new Map(UNITS);
export const EN_TO_RU = new Map(UNITS.map(([ru, en]) => [en, ru]));
EN_TO_RU.set('minutes', 'мин').set('hour', 'ч').set('kg', 'кг');

const SUPER: Record<string, string> = { '⁻': '-', '⁰': '0', '¹': '1', '²': '2', '³': '3', '⁴': '4', '⁵': '5', '⁶': '6', '⁷': '7', '⁸': '8', '⁹': '9' };

/**
 * Запись единицы по-русски («км/ч», «м/с²», «Н·м²/кг²», «Дж/(моль·К)») →
 * запись для math.js. Неизвестное обозначение — ошибка с его именем.
 */
export function ruUnitToEn(unit: string): string | { error: string } {
  let s = unit.trim().replace(/[·∙⋅×*]/g, ' ');
  // Степени надстрочными знаками: «м²», «моль⁻¹».
  s = s.replace(/[⁻⁰¹²³⁴⁵⁶⁷⁸⁹]+/g, (w) => `^${[...w].map((c) => SUPER[c]).join('')}`);
  let error: string | null = null;
  s = s.replace(/[A-Za-zА-Яа-яЁё]+/g, (w) => {
    const en = RU_TO_EN.get(w);
    if (en) return en;
    // Латинские имена math.js тоже принимаются (m/s, kg).
    if (/^[A-Za-z]+$/.test(w)) return w;
    error ??= `Неизвестная единица «${w}»`;
    return w;
  });
  return error ? { error } : s.replace(/\s+/g, ' ').trim();
}

/** Запись единицы math.js → по-русски: «m / s^2» → «м/с²», «N m» → «Н·м». */
export function enUnitToRu(unit: string): string {
  const sup: Record<string, string> = { '-': '⁻', '1': '¹', '2': '²', '3': '³', '4': '⁴', '5': '⁵', '6': '⁶', '7': '⁷', '8': '⁸', '9': '⁹', '0': '⁰' };
  return unit
    // Скобки вокруг числителя не нужны: «(kg m) / s^2» → «кг·м/с²»; в знаменателе — остаются.
    .replace(/^\(([^()]+)\)\s*\//, '$1 /')
    .replace(/[A-Za-z]+/g, (w) => EN_TO_RU.get(w) ?? w)
    .replace(/\^(-?\d+)/g, (_, d: string) => [...d].map((c) => sup[c]).join(''))
    .replace(/\s*\/\s*/g, '/')
    .replace(/\s+/g, '·');
}
