/** Поиск по названию, обозначениям, теме и ключевым словам; пустой запрос — всё. */
export function searchReference(query: string, topic?: string): { topic: RefTopic; item: RefFormula }[] {
  const words = query.toLowerCase().replace(/ё/g, 'е').split(/\s+/).filter(Boolean);
  const out: { topic: RefTopic; item: RefFormula }[] = [];
  for (const t of REFERENCE) {
    if (topic && t.id !== topic) continue;
    for (const item of t.items) {
      const hay = [item.title, item.notes, t.title, ...item.keywords].join(' ').toLowerCase().replace(/ё/g, 'е');
      if (words.every((w) => hay.includes(w))) out.push({ topic: t, item });
    }
  }
  return out;
}
